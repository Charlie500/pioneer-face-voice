import fs from 'node:fs/promises';
const root = new URL('../src/shaders/', import.meta.url);
const vertex = await fs.readFile(new URL('face.vert.glsl', root), 'utf8');
const fragment = await fs.readFile(new URL('face.frag.glsl', root), 'utf8');
await fs.writeFile(new URL('face-shader.js', root), `// Generated by npm run shaders.\nexport const faceVertexShader = ${JSON.stringify(vertex)};\nexport const faceFragmentShader = ${JSON.stringify(fragment)};\n`);
console.log('Updated face shader module.');
